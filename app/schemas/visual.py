class ImageValidationReport(Schema):
    valid: bool
    errors: list[ImageValidationError] = Field(default_factory=list)
    checks: list[str] = Field(default_factory=list)  # every check that ran
    measured: MeasuredImage | None = None
    validator: str

    @model_validator(mode="after")
    def _consistent(self) -> ImageValidationReport:
        if self.valid == bool(self.errors):
            raise ValueError("a report is valid exactly when it has no errors")
        return self


