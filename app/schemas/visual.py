class VisualResult(Schema):
    status: Literal["complete", "partial", "failed"]  # failed: a required visual could not be produced
    plan: VisualPlan
    plan_artifact_id: str
    artifacts: list[Artifact] = Field(default_factory=list)  # the VISUAL_PLAN, then every IMAGE_ASSET
    assets: list[VisualAssetRef] = Field(default_factory=list)
    failures: list[VisualFailure] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def _consistent(self) -> VisualResult:
        planned = {r.visual_id for r in self.plan.requirements}
        done = [a.visual_id for a in self.assets]
        failed = [f.visual_id for f in self.failures]
        if len(done) != len(set(done)) or set(done) & set(failed) or (set(done) | set(failed)) != planned:
            raise ValueError("every planned visual is either an asset or a failure, once")
        if {a.artifact_id for a in self.artifacts} != {self.plan_artifact_id} | {a.artifact_id for a in self.assets}:
            raise ValueError("artifacts must be the visual plan and the image assets")
        expected = ("failed" if any(f.required for f in self.failures)
                    else "partial" if self.failures else "complete")
        if self.status != expected:
            raise ValueError(f"status must be '{expected}'")
        return self

    def for_section(self, section_id: str) -> list[VisualAssetRef]:
        return [a for a in self.assets if a.lesson_section_id == section_id]
