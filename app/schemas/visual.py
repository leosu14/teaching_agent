# --- Image generation ------------------------------------------------------------------------


class ImageGenerationRequest(Schema):
    prompt: str = Field(min_length=1)
    negative_prompt: str | None = None
    aspect_ratio: str | None = None
    width: int = Field(default=1280, ge=64, le=4096)
    height: int = Field(default=720, ge=64, le=4096)
    style: str | None = None
    seed: int | None = Field(default=None, ge=0)

    @model_validator(mode="after")
    def _size_matches_ratio(self) -> ImageGenerationRequest:
        if self.aspect_ratio is not None and not aspect_matches(self.width, self.height, self.aspect_ratio):
            raise ValueError(f"{self.width}x{self.height} does not have aspect ratio {self.aspect_ratio}")
        return self


class ImageGenerationResult(Schema):
    asset_id: str
    provider: str
    model: str
    width: int
    height: int
    format: str
    metadata: GenerationAttribution
    storage: StoredObject
    usage: ImageUsage


