class ImageAsset(Schema):
    """Metadata of an IMAGE_ASSET artifact. The binary lives in the object store at `object.uri`."""

    asset_id: str  # content-derived: identical bytes, identical asset id
    visual_id: str
    plan_id: str
    lesson_section_id: str
    visual_type: VisualType
    purpose: str
    description: str
    origin: ImageOrigin
    object: StoredObject
    width: int
    height: int
    format: str
    attribution: VisualAttribution
    selection: SelectionRecord | None = None
    validation: ImageValidationReport

    @model_validator(mode="after")
    def _consistent(self) -> ImageAsset:
        expected = "search" if self.origin == "search" else "generated"
        if self.attribution.kind != expected:
            raise ValueError(f"a {self.origin} image needs {expected} attribution")
        if not self.validation.valid:
            raise ValueError("an image asset must pass validation")
        if self.origin == "search" and self.selection is None:
            raise ValueError("a searched image must record how it was selected")
        return self


