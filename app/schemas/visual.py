"""Visual asset schemas. Domain- and provider-independent.

Chain: a VisualPlan lists VisualRequirements -> each fulfilled requirement becomes one IMAGE_ASSET artifact
(an ImageAsset) -> whose attribution records where the image came from: the external source of a searched
image, or the provider, model and prompt hash of a generated one. Attribution is copied from providers by
code, never written by a model, and it is separate from the lesson's textual citation chain
(Citation -> Evidence -> Source): an image is never evidence.
"""

from __future__ import annotations

import re
from datetime import datetime
from enum import Enum
from typing import Annotated, Literal

from pydantic import Field, field_validator, model_validator

from app.schemas.artifact import Artifact, StoredObject
from app.schemas.common import Schema

# --- Visual types ---------------------------------------------------------------------------


class VisualType(str, Enum):
    """What kind of picture a visual is. Add members as new kinds are needed; nothing is subject-specific."""

    PHOTO = "photo"
    ILLUSTRATION = "illustration"
    DIAGRAM = "diagram"
    CHART = "chart"
    MAP = "map"
    ICON = "icon"
    GENERATED_VISUAL = "generated_visual"

    @classmethod
    def parse(cls, value: str | None) -> VisualType | None:
        """Map a provider's label to a visual type; None when it names nothing we know."""
        if not value:
            return None
        key = value.strip().lower().replace("-", "_").replace(" ", "_")
        aliases = {"photograph": "photo", "image": "photo", "drawing": "illustration", "vector": "illustration",
                   "clipart": "illustration", "graph": "chart", "figure": "diagram"}
        try:
            return cls(aliases.get(key, key))
        except ValueError:
            return None


# Real-world depictions must come from a real source: a generated "photo" or "map" would mislead learners.
SEARCH_ONLY = frozenset({VisualType.PHOTO, VisualType.MAP})
GENERATE_ONLY = frozenset({VisualType.GENERATED_VISUAL})

VisualSource = Literal["search", "generate"]
ImageOrigin = Literal["search", "generated"]

ASPECT_RATIO = re.compile(r"^([1-9]\d?):([1-9]\d?)$")
URL_LIKE = re.compile(r"(https?://|www\.|data:\w+/|file://)", re.IGNORECASE)
ASPECT_TOLERANCE = 0.02  # relative difference allowed between an image's ratio and the expected one


def aspect_value(ratio: str) -> float:
    match = ASPECT_RATIO.match(ratio)
    if not match:
        raise ValueError(f"aspect ratio must look like '16:9', got {ratio!r}")
    return int(match.group(1)) / int(match.group(2))


def aspect_matches(width: int, height: int, ratio: str, tolerance: float = ASPECT_TOLERANCE) -> bool:
    expected = aspect_value(ratio)
    return abs(width / height - expected) / expected <= tolerance


# --- Visual planning ------------------------------------------------------------------------


class VisualRequirement(Schema):
    visual_id: str = Field(pattern=r"^[A-Za-z0-9_.-]{1,64}$")
    purpose: str = Field(min_length=1)
    lesson_section_id: str
    concept: str = Field(min_length=1)
    description: str = Field(min_length=1)  # what the image shows; also its alt text
    visual_type: VisualType
    preferred_source: VisualSource
    search_query: str | None = None
    generation_prompt: str | None = None
    aspect_ratio: str = "16:9"
    required: bool = True
    attribution_required: bool = True

    @field_validator("aspect_ratio")
    @classmethod
    def _ratio(cls, value: str) -> str:
        aspect_value(value)
        return value

    @model_validator(mode="after")
    def _consistent(self) -> VisualRequirement:
        for name in ("purpose", "concept", "description", "search_query", "generation_prompt"):
            value = getattr(self, name)
            if value and URL_LIKE.search(value):
                raise ValueError(f"{name} must not contain a URL; images are found or generated by tools")
        if self.preferred_source == "search" and not (self.search_query or "").strip():
            raise ValueError(f"visual {self.visual_id}: a searched visual needs a search_query")
        if self.preferred_source == "generate" and not (self.generation_prompt or "").strip():
            raise ValueError(f"visual {self.visual_id}: a generated visual needs a generation_prompt")
        if self.visual_type in SEARCH_ONLY and self.preferred_source != "search":
            raise ValueError(f"visual {self.visual_id}: a {self.visual_type.value} must be searched, not generated")
        if self.visual_type in GENERATE_ONLY and self.preferred_source != "generate":
            raise ValueError(f"visual {self.visual_id}: a {self.visual_type.value} must be generated")
        return self

    def sources(self) -> list[VisualSource]:
        """Where to look, in order: the preferred source, then the other one when this visual allows it."""
        order: list[VisualSource] = [self.preferred_source]
        if self.preferred_source == "search" and self.generation_prompt and self.visual_type not in SEARCH_ONLY:
            order.append("generate")
        if self.preferred_source == "generate" and self.search_query and self.visual_type not in GENERATE_ONLY:
            order.append("search")
        return order


class VisualPlanProposal(Schema):
    """What the model proposes. The system assigns the plan id and checks it against the lesson."""

    requirements: list[VisualRequirement] = Field(default_factory=list)
    rationale: str = ""

    @field_validator("requirements")
    @classmethod
    def _unique(cls, requirements: list[VisualRequirement]) -> list[VisualRequirement]:
        ids = [r.visual_id for r in requirements]
        if len(ids) != len(set(ids)):
            raise ValueError("visual ids must be unique")
        return requirements


class VisualPlan(VisualPlanProposal):
    plan_id: str
    lesson_title: str

    def requirement(self, visual_id: str) -> VisualRequirement:
        return next(r for r in self.requirements if r.visual_id == visual_id)


# --- Attribution (a metadata chain separate from textual citations) --------------------------


class ImageLicense(Schema):
    name: str = Field(min_length=1)
    url: str | None = None


class SearchAttribution(Schema):
    """Exactly what the image provider reported. Unknown fields stay None; nothing is filled in."""

    kind: Literal["search"] = "search"
    provider: str
    image_id: str
    provider_image_id: str
    image_url: str
    source_url: str  # the page the image is published on
    title: str
    creator: str | None = None
    publisher: str | None = None
    license: ImageLicense | None = None
    attribution_text: str | None = None
    retrieved_at: datetime


class GenerationAttribution(Schema):
    """Provenance of a generated image. It has no source URL: a generated image is never external evidence."""

    kind: Literal["generated"] = "generated"
    provider: str
    model: str
    generated_at: datetime
    prompt: str
    prompt_hash: str  # sha256 of the prompt as sent
    negative_prompt: str | None = None
    style: str | None = None
    seed: int | None = None
    width: int
    height: int
    ignored_parameters: list[str] = Field(default_factory=list)  # requested but unsupported by the provider
    provider_metadata: dict = Field(default_factory=dict)


VisualAttribution = Annotated[SearchAttribution | GenerationAttribution, Field(discriminator="kind")]


