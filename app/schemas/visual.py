class ImageSearchRequest(Schema):
    query: str = Field(min_length=1)
    visual_type: VisualType | None = None
    aspect_ratio: str | None = None
    language: str | None = None
    max_results: int = Field(default=8, ge=1, le=50)


class ImageSearchResult(Schema):
    """A candidate image, normalised from any provider. Provider-only fields are kept in `metadata`."""

    image_id: str  # stable: derived from provider and provider id
    provider: str
    provider_image_id: str
    url: str
    thumbnail_url: str | None = None
    title: str
    description: str = ""
    source_url: str
    publisher: str | None = None
    creator: str | None = None
    width: int = Field(ge=1)
    height: int = Field(ge=1)
    format: str  # MIME type as reported by the provider
    license: ImageLicense | None = None
    attribution_text: str | None = None
    visual_type: VisualType | None = None  # as reported by the provider, when it maps to a known type
    source_type: str = "unknown"
    tags: list[str] = Field(default_factory=list)
    rank: int = Field(ge=1)
    retrieved_at: datetime
    metadata: dict = Field(default_factory=dict)

    def attribution(self) -> SearchAttribution:
        return SearchAttribution(
            provider=self.provider, image_id=self.image_id, provider_image_id=self.provider_image_id,
            image_url=self.url, source_url=self.source_url, title=self.title, creator=self.creator,
            publisher=self.publisher, license=self.license, attribution_text=self.attribution_text,
            retrieved_at=self.retrieved_at,
        )


